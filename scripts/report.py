"""results/ledger.sqlite → results/summary.json + RESULTS.md (every number on the README comes from here)."""
import json, sqlite3, statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ARMS = ["single", "swarm", "swarm_nocritic"]
TASKS = ["alignment", "kabsch", "nussinov"]


def main():
    c = sqlite3.connect(ROOT / "results" / "ledger.sqlite"); c.row_factory = sqlite3.Row
    runs = [dict(r) for r in c.execute("SELECT * FROM runs ORDER BY task, arm, rep")]
    calls = [dict(r) for r in c.execute("SELECT * FROM calls")]
    for r in runs:
        r["cands"] = json.loads(r["candidates_hidden"])
        r["refines"] = sum(1 for k in calls if k["run_id"] == r["run_id"] and k["role"] == "refiner" and k["ok"])
        r["retries"] = sum(1 for k in calls if k["run_id"] == r["run_id"] and k["attempt"] == 2)
    arm = {}
    for a in ARMS:
        rs = [r for r in runs if r["arm"] == a]
        if not rs: continue
        arm[a] = {"runs": len(rs), "all_pass_runs": sum(r["all_pass"] for r in rs),
                  "hidden_pass_rate": round(sum(r["hidden_passed"] for r in rs) / sum(r["hidden_total"] for r in rs), 4),
                  "mean_calls": round(st.mean(r["calls"] for r in rs), 2), "mean_tokens": round(st.mean(r["tokens"] for r in rs)),
                  "median_wall_s": round(st.median(r["wall_s"] for r in rs), 1), "cost_usd": round(sum(r["cost_usd"] for r in rs), 4),
                  "first_try_all_pass": sum(1 for r in rs if r["cands"] and r["cands"][0] == r["hidden_total"]),
                  "any_candidate_all_pass": sum(1 for r in rs if any(x == r["hidden_total"] for x in r["cands"])),
                  "runs_with_refine": sum(1 for r in rs if r["refines"]),
                  "refine_when_already_correct": sum(1 for r in rs if r["refines"] and r["cands"] and
                                                    max(r["cands"][: (1 if a == "single" else 3)]) == r["hidden_total"]),
                  "agent_retries": sum(r["retries"] for r in rs),
                  "candidates_correct": sum(sum(x == r["hidden_total"] for x in r["cands"]) for r in rs),
                  "candidates": sum(len(r["cands"]) for r in rs)}
    cell = {f"{t}/{a}": [f"{r['hidden_passed']}/{r['hidden_total']}" for r in runs if r["task"] == t and r["arm"] == a]
            for t in TASKS for a in ARMS}
    out = {"model": runs[0]["model"] if runs else None, "arms": arm, "cells": cell,
           "total_cost_usd": round(sum(r["cost_usd"] for r in runs), 4), "total_calls": len(calls),
           "failed_calls": sum(1 for k in calls if not k["ok"])}
    (ROOT / "results" / "summary.json").write_text(json.dumps(out, indent=1))

    L = ["# Results", "", f"Generated by `scripts/report.py` from `results/ledger.sqlite`. Model: Claude {out['model']} "
         f"(headless `claude -p`, no tools). Call cap per run: 6 for every arm. Hidden tests never shown to agents.", "",
         "## Per arm", "", "| Arm | Runs | All hidden tests passed | Hidden tests passed | First draft fully correct | "
         "Any candidate fully correct | Candidates fully correct | Mean calls | Mean tokens | Median wall time | Refine calls spent on an already correct answer |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for a, s in arm.items():
        L.append(f"| `{a}` | {s['runs']} | {s['all_pass_runs']}/{s['runs']} | {100*s['hidden_pass_rate']:.1f}% | "
                 f"{s['first_try_all_pass']}/{s['runs']} | {s['any_candidate_all_pass']}/{s['runs']} | {s['candidates_correct']}/{s['candidates']} | {s['mean_calls']} | "
                 f"{s['mean_tokens']:,} | {s['median_wall_s']} s | {s['refine_when_already_correct']}/{s['runs_with_refine']} |")
    L += ["", "## Per task (hidden tests passed by the final answer, one entry per rep)", "", "| Task | " + " | ".join(f"`{a}`" for a in ARMS) + " |",
          "|---|" + "---|" * len(ARMS)]
    for t in TASKS:
        L.append(f"| {t} | " + " | ".join(", ".join(cell[f'{t}/{a}']) or "–" for a in ARMS) + " |")
    L += ["", f"Total: {out['total_calls']} model calls ({out['failed_calls']} failed and retried or dropped), "
          f"${out['total_cost_usd']} at list price (paid through the Claude Code plan).", ""]
    sw, si = arm.get("swarm"), arm.get("single")
    if sw and si:
        L += [f"Swarm vs single: {sw['mean_tokens'] / si['mean_tokens']:.1f}x the tokens, "
              f"{sw['median_wall_s'] / si['median_wall_s']:.1f}x the median wall time, same final correctness.", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
